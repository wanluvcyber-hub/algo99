function obstTrace(p, withR, r) {
  const n = p.length, C = Array.from({ length: n }, () => Array(n).fill(null)), R = Array.from({ length: n }, () => Array(n).fill(null));
  const lab = range(1, n + 1);
  const get = (i, j) => i > j ? 0 : C[i - 1][j - 1];
  const pn = (cur, src, ok) => {
    const a = [tbl('p[i] — ความน่าจะเป็นที่คีย์ i ถูกค้นหา', [p], { cl: lab, rl: ['p'] }),
      tbl('C[i][j] — ต้นทุนเฉลี่ยต่ำสุดของคีย์ i..j', C, { cl: lab, rl: lab, cur: cur ? [cur[0] - 1, cur[1] - 1] : null, src: (src || []).map(([a, b]) => [a - 1, b - 1]), ok: ok || [] })];
    if (withR) a.push(tbl('R[i][j] — คีย์ที่เป็น Root ของช่วง i..j', R, { cl: lab, rl: lab, cur: cur ? [cur[0] - 1, cur[1] - 1] : null, ok: (ok || []) }));
    return a;
  };
  for (let i = 1; i <= n; i++) { C[i - 1][i - 1] = p[i - 1]; R[i - 1][i - 1] = i; }
  r.add('diag', `ช่วงยาว 1 คีย์: C[i][i] = p[i-1] → ${p.map((x, i) => `C[${i + 1}][${i + 1}] = ${x}`).join(', ')}${withR ? ' · R[i][i] = i' : ''}`, pn());
  for (let d = 1; d < n; d++) for (let i = 1; i <= n - d; i++) {
    const j = i + d, s = rnd(range(i, j + 1).reduce((a, k) => a + p[k - 1], 0)); let best = INF, bk = 0;
    for (let k = i; k <= j; k++) {
      const a = get(i, k - 1), b = get(k + 1, j), val = rnd(a + b + s);
      r.add('val', `C[${i}][${j}], ลอง Root = คีย์ ${k}: C[${i}][${k - 1}] + C[${k + 1}][${j}] + Σp(${i}..${j}) = ${a} + ${b} + ${s} = <b>${val}</b>${val < best ? ' ← ดีที่สุดถึงตอนนี้' : ''}`,
        pn([i, j], [...(k - 1 >= i ? [[i, k - 1]] : []), ...(k + 1 <= j ? [[k + 1, j]] : [])]));
      if (val < best) { best = val; bk = k; }
    }
    C[i - 1][j - 1] = best; R[i - 1][j - 1] = bk;
    r.add('store', `C[${i}][${j}] = <b>${best}</b> ← เลือกคีย์ <b>${bk}</b> เป็น Root${i === 1 && j === n ? ' (นี่คือช่อง C[1,4] ที่โจทย์ถาม)' : ''}`, pn([i, j], [], []));
  }
  return { C, R, n, pn };
}
