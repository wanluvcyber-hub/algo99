function fibTrace(N, memoOn) {
  const nodes = [], st = [], val = [], r = Rec(), memo = {}, seen = {}; let calls = 0;
  const pn = cur => {
    const p = [treeP(memoOn ? 'ต้นไม้การเรียก (เขียว = memo ช่วยตัดการคำนวณ)' : 'ต้นไม้การเรียก Recursive ธรรมดา (แดง = คำนวณซ้ำโดยเปล่าประโยชน์)', nodes, st, val)];
    if (memoOn) p.push(tbl('memo[k] (ตารางช่วยจำ)', [range(0, N + 1).map(k => k in memo ? memo[k] : null)], { cl: range(0, N + 1), rl: ['memo'], cur: cur != null ? [0, cur] : null }));
    p.push(textP('จำนวนการเรียกฟังก์ชัน', `<b>${calls}</b> ครั้ง`));
    return p;
  };
  function fib(n, parent) {
    const id = nodes.length; nodes.push({ id, label: `fib(${n})`, parent }); st.push(1); val.push(null); calls++;
    const dup = !memoOn && seen[n]; seen[n] = true;
    r.add(memoOn ? 'def' : null, `เรียก fib(${n})`, pn(n));
    if (memoOn && n in memo) { st[id] = 3; val[id] = memo[n]; r.add('hit', `fib(${n}) มีใน memo แล้ว = ${memo[n]} → คืนค่าทันที ไม่ต้องคำนวณซ้ำ`, pn(n)); return memo[n]; }
    if (n <= 1) { st[id] = dup ? 4 : 2; val[id] = n; r.add(memoOn ? 'base' : null, `fib(${n}) = ${n} (base case)`, pn(n)); return n; }
    const v = fib(n - 1, id) + fib(n - 2, id);
    if (memoOn) memo[n] = v;
    st[id] = dup ? 4 : 2; val[id] = v;
    r.add(memoOn ? 'store' : null, dup ? `fib(${n}) = ${v} — <b>คำนวณซ้ำ</b> (เคยคำนวณไปแล้ว)` : `fib(${n}) = ${v}` + (memoOn ? ` → เก็บลง memo[${n}]` : ''), pn(n));
    return v;
  }
  fib(N, -1); return r.steps;
}
