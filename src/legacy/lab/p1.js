function changeSteps(D, n, r, pre) {
  const F = Array(n + 1).fill(INF); F[0] = 0;
  const pn = (cur, src, coin, ok) => [
    tbl('เหรียญที่มี D', [D], { cl: range(1, D.length + 1), cur: coin != null ? [0, D.indexOf(coin)] : null }),
    tbl('F[i] = จำนวนเหรียญน้อยสุดที่ทอนเงิน i บาท', [F], { rl: ['F'], cl: range(0, n + 1), cur: cur != null ? [0, cur] : null, src: src || [], ok: ok || [] }),
  ];
  r.add('init', (pre || '') + 'เริ่มต้น: F[0] = 0 (ทอน 0 บาทใช้ 0 เหรียญ) ที่เหลือเป็น ∞ (ยังไม่รู้)', pn(0));
  for (let i = 1; i <= n; i++) for (const c of D) if (i >= c) {
    const cand = F[i - c] + 1, old = F[i]; F[i] = Math.min(F[i], cand);
    r.add('upd', `i=${i}, เหรียญ ${c}: F[${i - c}] + 1 = ${inf(F[i - c])} + 1 = ${cand} · เทียบกับค่าเดิม ${inf(old)} → F[${i}] = <b>${F[i]}</b>`, pn(i, [[0, i - c]], c));
  }
  const used = []; let x = n; while (x > 0) { const c = D.find(c => x >= c && F[x - c] + 1 === F[x]); used.push(c); x -= c; }
  r.add('ret', `คำตอบ F[${n}] = <b>${F[n]}</b> เหรียญ (ใช้เหรียญ ${used.join(' + ')})`, pn(n, [], null, [[0, n]]));
  return F;
}
